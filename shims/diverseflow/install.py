#!/usr/bin/env python3
"""Install the shared-layer shim into FlowBank's DiverseFlow stage.

DiverseFlow is stage 1 of FlowBank's precompute-and-reuse pipeline: an AFlow-style
search that generates a pool of candidate workflows. FlowBank ships a curated
portfolio and a trained selector, but neither can be reused here -- its splits
overlap our canonical test sets (203 of our 500 MBPP items match by task_id), so
scoring against a portfolio selected on them would leak test data into one of the
methods being ranked. The pipeline has to be re-run on the canonical splits, which
is what this shim makes possible.

Unlike the AFlow shim, no benchmark substitution is needed: DiverseFlow ships
native benchmark classes, operator sets and workspace templates for all five of
our datasets, MMLU-Pro included.

    python shims/diverseflow/install.py [--check]
"""

