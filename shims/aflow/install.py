MBPP_DAEMON_MARKER = "# --- shared-layer shim (agent_wf_v2) --- mbpp daemon guard v1"


def patch_mbpp_daemon_thread(repo) -> None:
    """Daemonise the mbpp benchmark's test-runner thread.

    benchmarks/mbpp.py run_with_timeout starts a plain threading.Thread for the
    generated code + asserts and abandons it on timeout. The thread is
    non-daemon, so every hung generated function (an infinite get_ludic on
    2026-08-24) leaks a live thread; they accumulate over a search and finally
    keep the interpreter alive after run.py ends -- aflow/mbpp sat wire-quiet
    for 3 hours twice. Same shape and same fix as the G-Designer family's
    guard thread (shims/gdesigner_family patch_daemon_guard).
    """
    import ast as _ast
    path = repo / "benchmarks" / "mbpp.py"
    text = path.read_text(encoding="utf-8")
    if MBPP_DAEMON_MARKER in text:
        report(True, "mbpp guard thread already daemonised")
        return
    anchor_line = "        thread = threading.Thread(target=target)\n        thread.start()"
    if anchor_line not in text:
        report(False, "mbpp daemonise: anchor not found")
        return
    text = text.replace(anchor_line,
                        "        thread = threading.Thread(target=target)\n"
                        "        " + MBPP_DAEMON_MARKER + "\n"
                        "        thread.daemon = True\n        thread.start()", 1)
    try:
        _ast.parse(text)
    except SyntaxError as exc:
        report(False, f"mbpp daemonise: does not parse: {exc}")
        return
    path.write_text(text, encoding="utf-8")
    report(True, "mbpp guard thread daemonised")


