def patch_code_execution() -> None:
    """Bound execution of model-written code with a process that can be killed.

    AFlow has the same non-terminating pattern as MaAS -- ProcessPoolExecutor in a
    `with` block, cancelled but not killed on timeout, so the block's exit waits on
    the runaway child forever -- and additionally runs generated test cases through
    a bare `exec(test_code, globals())` with no timeout at all.
    """
    targets = sorted((REPO / "workspace").glob("*/workflows/template/operator.py"))
    targets += [p for p in [REPO / "scripts" / "operators.py",
                            REPO / "scripts" / "operator.py"] if p.exists()]
    tally: dict[str, int] = {}
    for path in targets:
        outcome = exec_guard_patch.patch_file(path)
        tally[outcome] = tally.get(outcome, 0) + 1
    report(tally.get("patched", 0) + tally.get("already", 0) > 0,
           "generated-code execution guarded ("
           + ", ".join(f"{v} {k}" for k, v in sorted(tally.items())) + ")")


