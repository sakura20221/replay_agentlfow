#!/usr/bin/env python3
"""Install the shared-layer shim into AFlow.

Four things happen:

1. shared benchmark classes are added (see shared_benchmarks.py for why AFlow
   needs a scoring shim rather than just data);
2. the evaluator's dispatch table and run.py's EXPERIMENT_CONFIGS gain five
   entries -- note the repo ships `benchmarks/amc.py` but never registered AMC,
   so AMC was unreachable even before we arrived;
3. data files are *written*, not linked, because the field names differ per
   benchmark: AFlow's amc.py reads `problem["question"]` while the canonical
   split calls it `problem`. Adapting here keeps the canonical data and its
   sha256 untouched;
4. `download(["datasets"], ...)` is made non-fatal: AFlow's data lives on Google
   Drive, which is unreachable from this host, and the call otherwise aborts
   every run before it starts.

    python shims/aflow/install.py [--check]
"""

